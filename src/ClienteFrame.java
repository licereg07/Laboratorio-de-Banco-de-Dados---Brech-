    public void preencherTabela() {
        ClienteDAO cDAO = new ClienteDAO();
        List<Cliente> lista = cDAO.listarTodos();

        DefaultTableModel model = (DefaultTableModel) tblClientes.getModel();
        model.setNumRows(0);

        for (Cliente c : lista) {
            model.addRow(new Object[]{
                c.getId(),
                c.getNome(),
                c.getCpf(),
                c.getTelefone(),
                c.getEmail()
            });
        }
    }

    

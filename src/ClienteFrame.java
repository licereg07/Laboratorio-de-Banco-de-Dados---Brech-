    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
      if (txtNome.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, preencha pelo menos o Nome do Cliente!");
            return;
        }
      Cliente c = new Cliente();
        c.setNome(txtNome.getText());
        c.setCpf(txtCPF.getText());
        c.setTelefone(txtTelefone.getText());
        c.setEmail(txtEmail.getText());

        ClienteDAO cDAO = new ClienteDAO();
        
        if (ehEdicao) {
            c.setId(idEmEdicao);
            cDAO.editar(c);
            JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
        } else {
            cDAO.inserir(c);
            JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!");
        }
        
        preencherTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
        int linha = tblClientes.getSelectedRow();
        if (linha != -1) {
            idEmEdicao = Integer.parseInt(tblClientes.getValueAt(linha, 0).toString());
            ehEdicao = true;

            txtNome.setText(tblClientes.getValueAt(linha, 1).toString());
            txtCPF.setText(tblClientes.getValueAt(linha, 2) != null ? tblClientes.getValueAt(linha, 2).toString() : "");
            txtTelefone.setText(tblClientes.getValueAt(linha, 3) != null ? tblClientes.getValueAt(linha, 3).toString() : "");
            txtEmail.setText(tblClientes.getValueAt(linha, 4) != null ? tblClientes.getValueAt(linha, 4).toString() : "");
        }
    }//GEN-LAST:event_tblClientesMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linha = tblClientes.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para editar!");
            return;
        }

        int id = Integer.parseInt(tblClientes.getValueAt(linha, 0).toString());

        Cliente c = new Cliente();
        c.setId(id);
        c.setNome(txtNome.getText());
        c.setCpf(txtCPF.getText());
        c.setTelefone(txtTelefone.getText());
        c.setEmail(txtEmail.getText());

        ClienteDAO cDAO = new ClienteDAO();
        cDAO.editar(c);

        JOptionPane.showMessageDialog(this, "Cliente editado com sucesso!");

        preencherTabela();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblClientes.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para excluir!");
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir este cliente?", "Confirmar Exclusão", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            int id = Integer.parseInt(tblClientes.getValueAt(linha, 0).toString());
            ClienteDAO cDAO = new ClienteDAO();
            cDAO.excluir(id);

            JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!");
            preencherTabela();
            btnLimparActionPerformed(evt);
        }   
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed
        txtNome.setText("");
        txtCPF.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");

        ehEdicao = false;
        idEmEdicao = -1;

        tblClientes.clearSelection();
        btnSalvar.setEnabled(true);
        txtNome.requestFocus();
    }//GEN-LAST:event_btnLimparActionPerformed

